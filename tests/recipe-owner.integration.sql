-- Run within a transaction; the caller rolls back all fixtures and changes.
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from public.profiles limit 1),'role','authenticated','is_anonymous',false)::text,true);
select set_config('test.owner',auth.uid()::text,true);
select set_config('test.owner_submission',gen_random_uuid()::text,true);
insert into storage.objects(bucket_id,name) values('community_recipe_images',auth.uid()::text||'/'||current_setting('test.owner_submission')||'/cover.jpg');
set local role authenticated;
do $$
declare sid uuid:=current_setting('test.owner_submission')::uuid; p jsonb; saved jsonb; changed jsonb; rid uuid; version timestamptz; blocked boolean;
begin
  if auth.uid() is null then raise exception 'Test requires a profile'; end if;
  p:=jsonb_build_object('short_description','Fixture recipe summary','title','Owner test','description','Original description','difficulty','Easy','total_time_minutes',20,'servings',2,'cover_image','community:'||auth.uid()::text||'/'||sid::text||'/cover.jpg','ingredients',jsonb_build_array(jsonb_build_object('name','Water','group_name','Main','amount',500,'unit','ml')),'steps',jsonb_build_array(jsonb_build_object('instruction','Boil','is_final',true)),'tag_ids','[]'::jsonb,'tag_names','[]'::jsonb,'nutrition',null);
  saved:=public.save_recipe_submission(sid,p,true,null); rid:=(saved->>'recipe_id')::uuid;version:=(saved->>'updated_at')::timestamptz;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',gen_random_uuid(),'role','authenticated')::text,true);
  blocked:=false;
  begin perform public.update_recipe_submission(sid,p,version); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Non-owner edited a recipe'; end if;
  blocked:=false;
  begin perform public.delete_recipe_submission(sid,version); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Non-owner deleted a recipe'; end if;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',current_setting('test.owner'),'role','authenticated','is_anonymous',true)::text,true);
  blocked:=false;
  begin perform public.update_recipe_submission(sid,p,version); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Anonymous user edited a recipe'; end if;
  blocked:=false;
  begin perform public.delete_recipe_submission(sid,version); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Anonymous user deleted a recipe'; end if;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',current_setting('test.owner'),'role','authenticated','is_anonymous',false)::text,true);
  blocked:=false;
  begin perform public.update_recipe_submission(sid,jsonb_set(p,'{title}','""'),version); exception when others then blocked:=true; end;
  if not blocked then raise exception 'Incomplete publication accepted'; end if;
  blocked:=false;
  begin perform public.update_recipe_submission(sid,jsonb_set(p,'{cover_image}','"community:other-user/cover.jpg"'),version); exception when others then blocked:=true; end;
  if not blocked then raise exception 'Foreign image accepted'; end if;
  insert into public.saved_recipes(user_id,recipe_id) values(auth.uid(),rid);
  p:=jsonb_set(p,'{title}','"Updated owner recipe"');p:=jsonb_set(p,'{steps}',jsonb_build_array(jsonb_build_object('instruction','New first step'),jsonb_build_object('instruction','Serve','is_final',true)));
  changed:=public.update_recipe_submission(sid,p,version);
  if (changed->>'recipe_id')::uuid<>rid or (select title from public.recipes where id=rid)<>'Updated owner recipe' then raise exception 'Update changed ID or lost title'; end if;
  if (select count(*) from public.recipe_steps where recipe_id=rid)<>2 then raise exception 'Steps were not replaced'; end if;
  if not exists(select 1 from public.saved_recipes where user_id=auth.uid() and recipe_id=rid) then raise exception 'Update removed saves'; end if;
  blocked:=false;
  begin perform public.update_recipe_submission(sid,p,version); exception when serialization_failure then blocked:=true; end;
  if not blocked then raise exception 'Stale edit accepted'; end if;
  blocked:=false;
  begin perform public.delete_recipe_submission(sid,version); exception when serialization_failure then blocked:=true; end;
  if not blocked then raise exception 'Stale deletion accepted'; end if;
  changed:=public.delete_recipe_submission(sid,(changed->>'updated_at')::timestamptz);
  if changed->>'deleted'<>'true' or exists(select 1 from public.recipes where id=rid) or exists(select 1 from public.recipe_submissions where id=sid) then raise exception 'Deletion failed'; end if;
  if exists(select 1 from public.saved_recipes where recipe_id=rid) or exists(select 1 from public.recipe_steps where recipe_id=rid) then raise exception 'Deletion left recipe relations'; end if;
  saved:=public.save_recipe_submission(sid,p,false,null);
  perform public.delete_recipe_submission(sid,(saved->>'updated_at')::timestamptz);
  if exists(select 1 from public.recipe_submissions where id=sid) then raise exception 'Draft deletion failed'; end if;
end;
$$;
reset role;
select 'Owner edits/deletes, unchanged recipe ID/saves, stale-version protection, ownership, anonymous access, validation, cascade and draft deletion passed.' as result;
